"""failure_cases.py — provoke each failure class deliberately.

A verifier that never rejects anything proves nothing. This constructs a trace
per class, starting from the CONFORMING seed execution and applying one targeted
mutation, so whatever the verifier reports is attributable to that mutation and
nothing else. Each case records the mutated trace, the resulting ACR, and
whether the expected class was actually raised.

    python failure_cases.py

Cases cover both finding families:
  PROCESS_CONFORMANCE   STRUCTURAL, GUARD_PRE, GUARD_POST, COMPLETENESS
  TRACE_INTEGRITY       CONTINUITY, SCHEMA, LEDGER_MISMATCH, UNMEDIATED
plus a HOLD control, which must NOT fail — a missing asserted effect with the
frame intact is a retry, not a violation, and a suite that could not tell those
apart would be reporting noise.
"""

import copy
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from artefact import atf, verify                                  # noqa: E402

TASK_NAME = "hanoi3"
OUT = HERE / "failure_cases"


def build_execution(moves):
    """Drive world.py through `moves` and record it as a trace, exactly as the
    runner does. Used where a case needs a genuine, self-consistent execution
    rather than an edited one."""
    from world import Hanoi
    h = Hanoi(3)
    ev, led = [], []
    for disk, to in moves:
        pre = h.observe()
        cell = h.cell(disk, to)
        ok, reason = h.move(disk, to)
        post = h.observe()
        led.append({"operation_seq": len(led), "kind": "move", "disk": disk,
                    "to": to, "cell": cell, "pre": pre, "post": post,
                    "executed": ok,
                    "outcome": "executed" if ok else f"not_executed:{reason}",
                    "observed_at": 0})
        ev.append({"seq": len(ev), "layer": "SYS", "type": "action",
                   "action": cell or "move_invalid",
                   "args": {"disk": disk, "to": to}, "pre": pre, "post": post,
                   "applied": ok, "note": reason[:120], "observed_at": 0})
    pre = h.observe()
    led.append({"operation_seq": len(led), "kind": "report", "cell": "report",
                "pre": pre, "post": pre, "executed": True,
                "outcome": "executed", "observed_at": 0})
    ev.append({"seq": len(ev), "layer": "SYS", "type": "report",
               "action": "report", "args": {}, "pre": pre, "post": pre,
               "applied": True, "observed_at": 0})
    task = json.loads((HERE / "tasks" / f"{TASK_NAME}.task.json")
                      .read_text(encoding="utf-8"))
    return {"atf_version": "1.0", "run_id": "constructed", "task": TASK_NAME,
            "artefact_ref": None,
            "agent": {"framework": "constructed", "model": "none"},
            "store_schema": task["store_schema"], "scope": task["scope"],
            "provenance_default": "runtime_observed",
            "harness": "hanoi-v1", "direction": "constructed",
            "unapplied_events_recorded": True,
            "events": ev, "operation_ledger": led}


def seed_trace(adf):
    d = atf.RUNS / adf["created_from_run"] / "trace.json"
    return json.loads(d.read_text(encoding="utf-8"))


def set_field(tr, i, field, value):
    """Change event i's PRE and event i-1's POST together.

    Editing a pre-state alone would break the state chain and raise CONTINUITY,
    so the mutation would not be testing what it claims to. Moving both keeps
    the chain intact and isolates the guard.
    """
    tr["events"][i]["pre"][field] = value
    if i > 0:
        tr["events"][i - 1]["post"][field] = value


# --------------------------------------------------------------------------- #
# one function per case: takes the conforming trace, returns (trace, note)     #
# --------------------------------------------------------------------------- #
def case_structural(tr):
    """A DIFFERENT legal solution, generated by driving the world.

    Built by execution rather than by editing the seed, so the state chain and
    the ledger are internally consistent and the only thing wrong is that this
    is not the recorded path. Editing events in place would break continuity as
    well, and the finding would no longer be attributable to structure alone.
    """
    return build_execution([(1, "B"), (2, "C"), (1, "C"),
                            (3, "B"), (1, "A"), (2, "B"), (1, "B"),
                            (3, "C"), (1, "C"), (2, "A"), (1, "A"),
                            (2, "C"), (1, "C")]),         "a different legal solve, executed rather than edited"


def case_guard_pre(tr):
    """Falsify the guard the third move depends on, chain kept intact."""
    a = tr["events"][3]["action"]
    field = "legal_" + a.split("_")[1]
    set_field(tr, 3, field, False)
    return tr, f"{field} set false at the pre-state of event 3 ({a})"


def case_guard_post(tr):
    """Break the FRAME: a field the cell neither asserts nor releases changes.

    Move cells release the configuration and the legality predicates, so the
    only framed field is `solved`. Setting it true early is an effect the cell
    never accounted for.
    """
    tr["events"][1]["post"]["solved"] = True
    tr["events"][2]["pre"]["solved"] = True
    return tr, "solved set true after event 1, which does not assert it"


def case_completeness(tr):
    """Stop while the puzzle is still unsolved.

    Truncating only the report is NOT enough: the exit guard already holds by
    then, so the alignment deletes the missing cell, still terminates, and
    reports STRUCTURAL. COMPLETENESS is raised only when no alignment reaches
    termination WITH the exit guard satisfied, so the run has to stop before
    `solved` is ever established.
    """
    keep = 4
    tr["events"] = tr["events"][:keep]
    tr["operation_ledger"] = (tr.get("operation_ledger") or [])[:keep]
    return tr, f"run truncated to {keep} events, ending unsolved"


def case_continuity(tr):
    """Break the state chain: event 2's pre no longer follows event 1's post."""
    tr["events"][2]["pre"]["config"] = "999|-|-"
    return tr, "event 2 pre-state config replaced, chain broken"


def case_schema(tr):
    """Put a value of the wrong type in a typed field."""
    tr["events"][2]["pre"]["solved"] = "yes"
    tr["events"][1]["post"]["solved"] = "yes"
    return tr, "solved (bool) given the string 'yes'"


def case_ledger_mismatch(tr):
    """Delete a ledger entry so the physical and audited histories disagree."""
    led = tr.get("operation_ledger") or []
    for i, o in enumerate(led):
        if o.get("cell", "").startswith("move_"):
            del led[i]
            break
    return tr, "one classified ledger operation deleted"


def case_unmediated(tr):
    """An operation that executed without classifying to any cell."""
    led = tr.get("operation_ledger") or []
    led.append({"operation_seq": len(led), "kind": "move", "disk": 9, "to": "Z",
                "cell": None, "executed": True, "outcome": "executed",
                "pre": tr["events"][-1]["post"], "post": tr["events"][-1]["post"],
                "observed_at": 0})
    return tr, "executed operation appended with no cell"


def case_hold_control(tr):
    """CONTROL — must still conform.

    The final move asserts `solved := true`. Marking it unapplied and leaving
    the state unchanged is a missing asserted effect with the frame intact,
    which is a HOLD, not a violation. A duplicate of the move is appended so the
    process can still advance and terminate.
    """
    ev = tr["events"]
    last_move = copy.deepcopy(ev[-2])
    ev[-2]["applied"] = False
    ev[-2]["post"] = copy.deepcopy(ev[-2]["pre"])
    last_move["pre"] = copy.deepcopy(ev[-2]["post"])
    ev.insert(-1, last_move)
    for n, e in enumerate(ev):
        e["seq"] = n
    led = tr.get("operation_ledger") or []
    for i, o in enumerate(led):
        if o.get("cell") == "report":
            led.insert(i, {**copy.deepcopy(led[i - 1]), "operation_seq": 0})
            break
    for n, o in enumerate(led):
        o["operation_seq"] = n
    return tr, "final move recorded unapplied, then retried"


CASES = [
    ("structural",      "STRUCTURAL",      case_structural),
    ("guard_pre",       "GUARD_PRE",       case_guard_pre),
    ("guard_post",      "GUARD_POST",      case_guard_post),
    ("completeness",    "COMPLETENESS",    case_completeness),
    ("continuity",      "CONTINUITY",      case_continuity),
    ("schema",          "SCHEMA",          case_schema),
    ("ledger_mismatch", "LEDGER_MISMATCH", case_ledger_mismatch),
    ("unmediated",      "UNMEDIATED",      case_unmediated),
    ("hold_control",    None,              case_hold_control),
]


def main():
    adf = atf.load_adf(TASK_NAME)
    base = seed_trace(adf)
    OUT.mkdir(exist_ok=True)

    baseline = verify.check(base, adf)
    print(f"contract {adf['artefact_id'][:12]} v{adf['version']}  "
          f"seed {adf['created_from_run'][-4:]}")
    print(f"baseline (unmutated seed): {baseline['verdict']}\n")
    if baseline["verdict"] != "conforms":
        sys.exit("baseline does not conform — cannot attribute mutations")

    print(f"{'case':17}{'expected':17}{'verdict':11}{'raised':>7}  classes")
    results = []
    for name, expect, fn in CASES:
        tr, note = fn(copy.deepcopy(base))
        tr["run_id"] = f"FAILURECASE_{name}"
        acr = verify.check(tr, adf)
        cls = sorted({m["class"] for m in acr["misalignments"]})
        fams = sorted({m.get("family") for m in acr["misalignments"]})
        raised = (expect in cls) if expect else (acr["verdict"] == "conforms")
        atf.write_json(OUT / f"{name}.trace.json", tr)
        atf.write_json(OUT / f"{name}.acr.json", acr)
        results.append({"case": name, "expected": expect, "mutation": note,
                        "verdict": acr["verdict"], "classes": cls,
                        "families": fams, "as_expected": bool(raised),
                        "n_misalignments": len(acr["misalignments"])})
        print(f"{name:17}{str(expect or 'conforms (HOLD)'):17}{acr['verdict']:11}"
              f"{('YES' if raised else 'NO'):>7}  {','.join(cls) or '-'}")

    ok = sum(r["as_expected"] for r in results)
    atf.write_json(OUT / "_summary.json",
                   {"contract": {"artefact_id": adf["artefact_id"],
                                 "content_hash": adf["content_hash"],
                                 "seed_run": adf["created_from_run"]},
                    "baseline_verdict": baseline["verdict"],
                    "passed": ok, "total": len(results), "cases": results})
    print(f"\n{ok}/{len(results)} cases behaved as expected -> {OUT}")
    if ok != len(results):
        sys.exit(1)


if __name__ == "__main__":
    main()
